"""
Shared utilities for HeatSentinal Phase 1 satellite processing scripts.

Used by:
    process_landsat_lst.py
    process_sentinel_ndvi.py
    process_land_cover.py
    process_elevation.py
    build_phase1_dataset.py

Everything here is read-only with respect to the master grid: it never
creates a new grid, it only indexes the existing one so that satellite
rasters (30m Landsat, 10m Sentinel-2, etc.) can be aggregated onto it
without a Python loop over every one of the ~600,000 cells.

GRID ALIGNMENT TRICK (why this is fast)
----------------------------------------
backend/data/ncr_300m_grid.gpkg was generated by generate_ncr_grid.py using
box(x, y, x+300, y+300) tiles whose corners sit on exact multiples of 300m
in EPSG:6933 (World Cylindrical Equal Area), starting from an origin of
(0, 0) in that CRS. That means:

    col = round((centroid_x - 150) / 300)
    row = round((centroid_y - 150) / 300)

are GLOBAL integer grid coordinates for every cell -- no need to know the
grid's bounding box to compute them.

When we reproject+resample a source raster (Landsat 30m, Sentinel-2 10m,
NASADEM 30m) into EPSG:6933 at a resolution that evenly divides 300
(30 -> 10x10 blocks, 10 -> 30x30 blocks) AND we snap the destination
transform's origin to a multiple of 300m, every block of NxN resampled
pixels lands on exactly one 300m grid cell. We can then reshape the
resampled array into blocks and reduce with vectorized NumPy
(nanmean/nanmedian/nanstd/nanmin/nanmax/count) -- no per-cell loop, no
per-scene loop over cells, and it's all done in memory with arrays sized
to one Landsat/Sentinel scene at a time, not the whole NCR grid.
"""

