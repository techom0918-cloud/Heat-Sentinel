def field_quality_report(series: pd.Series, valid_range: Optional[tuple] = None) -> dict:
    total = len(series)
    numeric = pd.to_numeric(series, errors="coerce")
    valid = numeric.notna()
    if valid_range is not None:
        lo, hi = valid_range
        out_of_range = valid & ((numeric < lo) | (numeric > hi))
        valid &= ~out_of_range
    else:
        out_of_range = pd.Series(False, index=series.index)

    n_valid = int(valid.sum())
    report = {
        "total_cells": total,
        "valid_cells": n_valid,
        "missing_cells": int(total - numeric.notna().sum()),
        "out_of_range_cells": int(out_of_range.sum()),
        "coverage_pct": round(100.0 * n_valid / total, 2) if total else 0.0,
        "min": float(numeric[valid].min()) if n_valid else None,
        "max": float(numeric[valid].max()) if n_valid else None,
        "mean": float(numeric[valid].mean()) if n_valid else None,
        "median": float(numeric[valid].median()) if n_valid else None,
    }
    return report
