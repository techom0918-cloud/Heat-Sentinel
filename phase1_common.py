WGS84 = "EPSG:4326"

# Used to pack (col, row) grid indices into a single int64 lookup key.
# Grid indices for NCR (EPSG:6933 meters / 300) run well under 1e8, so
# this multiplier leaves headroom with no risk of collision or overflow.
_GRID_KEY_MULT = 1_000_000_000


# ============================================================
# GRID INDEX
# ============================================================

@dataclass
class GridIndex:
    """Maps global (col, row) 300m grid coordinates -> cell_id."""

    key_to_cell: pd.Series   # index = grid_key (int64), values = cell_id
    n_cells: int

    @staticmethod
    def col_row_from_xy(centroid_x: np.ndarray, centroid_y: np.ndarray):
        col = np.round((centroid_x - GRID_SIZE_M / 2) / GRID_SIZE_M).astype(np.int64)
        row = np.round((centroid_y - GRID_SIZE_M / 2) / GRID_SIZE_M).astype(np.int64)
        return col, row

    @staticmethod
    def make_key(col: np.ndarray, row: np.ndarray) -> np.ndarray:
        return col.astype(np.int64) * _GRID_KEY_MULT + row.astype(np.int64)

    def lookup(self, col: np.ndarray, row: np.ndarray) -> np.ndarray:
        """Vectorized (col,row) -> cell_id. Returns None (object dtype) where
        the block does not correspond to any NCR grid cell."""
        keys = self.make_key(col, row)
        return self.key_to_cell.reindex(keys).to_numpy()


def load_master_grid():
    """Load the existing 300m master grid. Raises with a clear message if
    it hasn't been generated yet -- callers should not silently create a
    new one."""
    import geopandas as gpd

    if not GRID_GPKG.exists():
        raise FileNotFoundError(
            f"Master grid not found at {GRID_GPKG}.\n"
            "Run `python generate_ncr_grid.py` first (Task 2) -- "
            "this script does not create a grid."
        )

    grid = gpd.read_file(GRID_GPKG, layer=GRID_LAYER)
    if grid.crs is None or grid.crs.to_string() != GRID_CRS:
        grid = grid.to_crs(GRID_CRS)

    required_cols = {"cell_id", "centroid_x", "centroid_y", "geometry"}
    missing = required_cols - set(grid.columns)
    if missing:
        raise RuntimeError(
            f"Master grid is missing expected column(s): {sorted(missing)}. "
            "Was it generated by the current generate_ncr_grid.py?"
        )

    if grid["cell_id"].duplicated().any():
        n_dupe = int(grid["cell_id"].duplicated().sum())
        raise RuntimeError(f"Master grid has {n_dupe} duplicate cell_id values.")

    return grid


def build_grid_index(grid) -> GridIndex:
    col, row = GridIndex.col_row_from_xy(
        grid["centroid_x"].to_numpy(dtype=np.float64),
        grid["centroid_y"].to_numpy(dtype=np.float64),
    )
    keys = GridIndex.make_key(col, row)
    series = pd.Series(grid["cell_id"].to_numpy(), index=keys)
    if series.index.duplicated().any():
        raise RuntimeError(
            "Grid index collision: two grid cells mapped to the same "
            "(col,row). This should not happen for a regular 300m tiling; "
            "the master grid may be corrupt."
        )
    return GridIndex(key_to_cell=series, n_cells=len(series))


def snapped_bounds(minx, miny, maxx, maxy, size=GRID_SIZE_M):
    """Expand a bounding box outward to the nearest multiple of `size`,
    so a destination raster transform built from it aligns exactly with
    the 300m grid."""
    return (
        np.floor(minx / size) * size,
        np.floor(miny / size) * size,
        np.ceil(maxx / size) * size,
        np.ceil(maxy / size) * size,
    )


def aggregate_aligned_array(values: np.ndarray, block: int):
    """Reshape a (rows, cols) array -- whose rows/cols are each exactly
    divisible by `block` and whose georeferencing origin is snapped to a
    300m multiple -- into 300m blocks and reduce with NaN-aware stats.

    `values` must already have NaN in place of nodata/masked pixels.

    Returns dict of 2D arrays (n_block_rows, n_block_cols): mean, median,
    std, min, max, count. `count` is the number of valid source pixels
    that fell in that 300m cell (used as the observation count).
    """
    rows, cols = values.shape
    if rows % block != 0 or cols % block != 0:
        raise ValueError(
            f"Array shape {values.shape} is not divisible by block size {block}; "
            "the caller must pad/crop to a block-aligned shape first."
        )

    n_br, n_bc = rows // block, cols // block
    reshaped = values.reshape(n_br, block, n_bc, block).transpose(0, 2, 1, 3)
    reshaped = reshaped.reshape(n_br, n_bc, block * block)

    count = np.sum(~np.isnan(reshaped), axis=2)
    with np.errstate(all="ignore"), warnings.catch_warnings():
        # Blocks with zero valid pixels legitimately produce all-NaN
        # reductions (e.g. a 300m cell entirely outside a scene's cloud
        # mask) -- that's expected, not a bug, so silence NumPy's warning
        # for it rather than letting it spam stdout per scene.
        warnings.filterwarnings("ignore", category=RuntimeWarning)
        mean = np.nanmean(reshaped, axis=2)
        median = np.nanmedian(reshaped, axis=2)
        std = np.nanstd(reshaped, axis=2)
        vmin = np.nanmin(np.where(count[..., None] > 0, reshaped, np.nan), axis=2)
        vmax = np.nanmax(np.where(count[..., None] > 0, reshaped, np.nan), axis=2)

    return {
        "mean": mean, "median": median, "std": std,
        "min": vmin, "max": vmax, "count": count,
    }


def majority_aligned_array(values: np.ndarray, block: int, valid_classes: list[int]):
    """Like aggregate_aligned_array but for categorical rasters: returns
    the dominant (mode) class and its fraction within each 300m cell,
    ignoring pixels whose class is not in valid_classes (nodata/masked).

    Uses a small lookup table to remap raw class codes -> compact indices,
    NOT np.isin(). For a several-hundred-million-pixel raster (this
    collection's tiles are enormous), np.isin's internal sort-based
    implementation allocates an int64 array sized to the *entire* input
    (confirmed: a 915M-pixel tile crashed trying to allocate 6.82 GiB for
    exactly that) -- a LUT indexed by pixel value costs nothing close to
    that regardless of raster size, since land-cover codes are always a
    handful of small integers.
    """
    rows, cols = values.shape
    if rows % block != 0 or cols % block != 0:
        raise ValueError(
            f"Array shape {values.shape} is not divisible by block size {block}."
        )
    n_br, n_bc = rows // block, cols // block

    min_v = int(min(valid_classes + [int(values.min())]))
    max_v = int(max(valid_classes + [int(values.max())]))
    lut = np.full(max_v - min_v + 1, -1, dtype=np.int16)
    for i, c in enumerate(valid_classes):
        lut[c - min_v] = i
    compact = lut[values - min_v]   # -1 where masked/invalid, else 0..K-1
    del lut

    reshaped = compact.reshape(n_br, block, n_bc, block).transpose(0, 2, 1, 3)
    reshaped = reshaped.reshape(n_br, n_bc, block * block)
    del compact

    K = len(valid_classes)
    counts = np.zeros((n_br, n_bc, K), dtype=np.int32)
    for i in range(K):
        counts[:, :, i] = np.sum(reshaped == i, axis=2)
    del reshaped

    valid_total = counts.sum(axis=2)
    best_idx = np.argmax(counts, axis=2)
    best_count = np.take_along_axis(counts, best_idx[..., None], axis=2)[..., 0]
    dom_class = np.array(valid_classes, dtype=np.int16)[best_idx]
    with np.errstate(invalid="ignore", divide="ignore"):
        dom_frac = np.where(valid_total > 0, best_count / np.maximum(valid_total, 1), 0.0)
    dom_class = np.where(valid_total > 0, dom_class, -1)

    return {"dominant_class": dom_class, "fraction": dom_frac.astype(np.float32),
            "valid_count": valid_total}


