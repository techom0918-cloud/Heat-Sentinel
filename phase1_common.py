def retry(fn: Callable, attempts: int = 3, delay_seconds: float = 2.0, label: str = ""):
    """Run fn() with up to `attempts` tries. Raises the last exception
    (with a full traceback string attached) if every attempt fails --
    never swallows the real error."""
    last_exc = None
    for i in range(1, attempts + 1):
        try:
            return fn()
        except Exception as exc:  # noqa: BLE001 -- we re-raise below
            last_exc = exc
            print(f"    [retry {i}/{attempts}] {label} failed: {exc!r}")
            if i < attempts:
                time.sleep(delay_seconds)
    assert last_exc is not None
    raise RuntimeError(
        f"{label} failed after {attempts} attempts.\n"
        f"{''.join(traceback.format_exception(type(last_exc), last_exc, last_exc.__traceback__))}"
    ) from last_exc


def gdal_retry_env():
    """rasterio.Env kwargs that make GDAL's own HTTP/VSICURL layer retry
    transient network failures before rasterio even sees an exception."""
    return dict(
        GDAL_HTTP_MAX_RETRY=3,
        GDAL_HTTP_RETRY_DELAY=1,
        GDAL_DISABLE_READDIR_ON_OPEN="EMPTY_DIR",
        CPL_VSIL_CURL_ALLOWED_EXTENSIONS=".tif,.TIF,.tiff",
        GDAL_CACHEMAX=512,
    )


