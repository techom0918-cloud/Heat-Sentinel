class Checkpoint:
    """Tracks which scenes have already been processed so a run can be
    interrupted (Ctrl+C, crash, network outage) and resumed without
    re-downloading completed scenes."""

    def __init__(self, path: Path):
        self.path = path
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.state = self._load()

    def _load(self) -> dict:
        if self.path.exists():
            try:
                return json.loads(self.path.read_text())
            except json.JSONDecodeError:
                print(f"    Checkpoint file {self.path} is corrupt -- starting fresh.")
        return {"completed": {}, "failed": {}}

    def is_done(self, scene_id: str) -> bool:
        return scene_id in self.state["completed"]

    def mark_done(self, scene_id: str, meta: dict):
        self.state["completed"][scene_id] = meta
        self.state["failed"].pop(scene_id, None)
        self._save()

    def mark_failed(self, scene_id: str, error: str):
        self.state["failed"][scene_id] = error
        self._save()

    def _save(self):
        self.path.write_text(json.dumps(self.state, indent=2, default=str))


def cache_path_for(cache_dir: Path, scene_id: str, suffix: str = ".npz") -> Path:
    cache_dir.mkdir(parents=True, exist_ok=True)
    safe_id = scene_id.replace("/", "_")
    return cache_dir / f"{safe_id}{suffix}"


